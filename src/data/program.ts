const A1_SECTIONS = COURSES.find((course) => course.id === 'a1')?.sections ?? []

function lectureId(ref: string): string {
  const [section, lecture] = ref.split('.')
  return `a1-s${section.padStart(2, '0')}-l${lecture.padStart(2, '0')}`
}

/** Программа занятия по его id; undefined — у субботних тестов и дней без привязки к курсу */
export function programFor(sessionId: string): SessionProgram | undefined {
  const refs = PROGRAM[sessionId]
  if (!refs) return undefined
  const sections = new Set<number>()
  const lectures: Lecture[] = []
  for (const ref of refs) {
    const id = lectureId(ref)
    const index = A1_SECTIONS.findIndex((section) => section.lectures.some((lecture) => lecture.id === id))
    const lecture = A1_SECTIONS[index]?.lectures.find((item) => item.id === id)
    if (!lecture) continue
    sections.add(index + 1)
    lectures.push(lecture)
  }
  return lectures.length > 0 ? { sections: [...sections].sort((a, b) => a - b), lectures } : undefined
}
